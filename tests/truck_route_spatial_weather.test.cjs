const assert=require("node:assert/strict");
const fs=require("node:fs");
const mod=require("../frontend/js/truck_route_spatial_weather_v1.js");
const html=fs.readFileSync("frontend/truck-route-file-viewer.html","utf8");
const viewer=fs.readFileSync("frontend/js/truck_route_geojson_viewer_v1.js","utf8");
assert.match(html,/id="sampleRouteWeather"/);
assert.match(html,/id="sampleWeatherResults"/);
assert.match(html,/truck_route_spatial_weather_v1.js/);
assert.match(viewer,/RainGuardRouteWeatherSamplerUI.setRoute/);
assert.doesNotMatch(html,/RAINGUARD_ROUTE_ACCESS_TOKEN|WEATHERAPI_API_KEY/);
const route={coordinates:[[39.1728,21.5433],[39.4,21.5],[39.8579,21.3891]],minutes:68.6};
const points=mod.samples(route.coordinates);
assert.equal(points.length,3);
assert.equal(points[0].lon,39.1728);
assert.equal(points[2].lon,39.8579);
assert.equal(points[1].arrivalTimeUtc,null);
assert.equal(points[1].forecastValidityAtPassage,"NOT_EVALUATED");
assert.ok(points[1].lon>39.1728&&points[1].lon<39.8579);
assert.throws(()=>mod.samples([[39.2,21.5],[90,21.5]]),/INVALID_ROUTE_POINT/);
const now=Date.parse("2026-11-11T12:00:00Z");
const epoch=Math.floor((now+3600*1000)/1000);
const payload={success:true,source:"weatherapi",retrievedAt:"2026-11-11T11:50:00Z",
 forecastHours:[{time_epoch:epoch,chance_of_rain:72,precip_mm:3.4}]};
let sample=mod.evaluate(payload,now);
assert.equal(sample.status,"FORECAST_AT_ROUTE_SAMPLE_AVAILABLE");
assert.equal(sample.rows[0].probabilityPct,72);
assert.equal(sample.safeToDrive,null);
assert.equal(sample.weatherTimeMatchedToArrival,false);
assert.equal(mod.evaluate({...payload,retrievedAt:"2026-11-11T09:00:00Z"},now).status,"UNAVAILABLE_OR_STALE");
assert.equal(mod.evaluate({...payload,forecastHours:[{time_epoch:epoch,chance_of_rain:null,precip_mm:0}]},now).rows.length,0);
assert.equal(mod.evaluate({...payload,forecastHours:[{time_epoch:epoch,chance_of_rain:101,precip_mm:0}]},now).rows.length,0);
(async()=>{
 let calls=[];
 const fetcher=async(url,options)=>{
   calls.push({url,options});
   return {ok:true,json:async()=>payload};
 };
 const out=await mod.inspectRoute(route,fetcher,now);
 assert.equal(calls.length,3);
 assert.equal(out.type,"SPATIAL_WEATHER_SNAPSHOT_NOT_ETA_MATCHED");
 assert.equal(out.perSegmentEtaAvailable,false);
 assert.equal(out.safeToDrive,null);
 assert.equal(out.operationalWarningApproved,false);
 assert.ok(calls.every(x=>x.url.startsWith("https://rainguard-ai.onrender.com/api/weather/weatherapi?lat=")));
 assert.ok(calls.every(x=>x.options.method==="GET"));
 const failed=await mod.inspectRoute(route,async()=>{throw Error("offline")},now);
 assert.ok(failed.samples.every(x=>x.forecast.status==="UNAVAILABLE_OR_STALE"));
 console.log("PASS spatial weather sampling: three requests, no ETA inference, stale/missing fail closed");
})().catch(e=>{console.error(e);process.exitCode=1});
