const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const html=fs.readFileSync("frontend/national-ai-os-v30.html","utf8");
const source=fs.readFileSync("frontend/js/source_adapter_v30.js","utf8");
const fusion=fs.readFileSync("frontend/js/rain_forecast_fusion_v32.js","utf8");
const backend=fs.readFileSync("main.py","utf8");
assert.match(html,/weatherapi_adapter_v32\.js\?v=weatherapi-v1/);
assert.ok(html.indexOf("weatherapi_adapter_v32.js")<html.indexOf("source_adapter_v30.js"));
assert.match(source,/official:\s*\{\s*enabled:\s*false/);
assert.match(source,/weatherAPI:\s*\{\s*enabled:\s*true/);
assert.doesNotMatch(fusion,/safe\(aa,city\)/);
assert.match(fusion,/WEATHERAPI/);
assert.match(fusion,/w&&w.available!==false/);
assert.match(backend,/WEATHERAPI_API_KEY = os\.getenv\("WEATHERAPI_API_KEY"\)/);
assert.match(backend,/@app\.get\("\/api\/weather\/weatherapi"\)/);
const proxySection=backend.slice(backend.indexOf("# WeatherAPI forecast"),backend.indexOf('@app.get("/rain-alert")'));
assert.doesNotMatch(proxySection,/detail": str\(exc\)/);

const code=fs.readFileSync("frontend/js/weatherapi_adapter_v32.js","utf8");
async function check(){
 const calls=[];
 const now=Math.floor(Date.now()/3600000)*3600+3600;
 const rows=Array.from({length:80},(_,i)=>({time_epoch:now+i*3600,precip_mm:i===1?2:0,chance_of_rain:i===1?75:10}));
 const ctx={window:{},fetch:async(url)=>{calls.push(url);return{ok:true,json:async()=>({success:true,forecastHours:rows})}}};
 vm.runInNewContext(code,ctx);
 const a=ctx.window.RG30.WeatherAPIAdapter;
 const good=await a.collect({name:"Jeddah",lat:21.5,lon:39.2});
 assert.equal(good.available,true);
 assert.equal(good.horizons["6h"].totalRainMm,2);
 assert.equal(good.horizons["6h"].rainProbability,75);
 assert.equal(good.horizons["72h"].available,true);
 assert.ok(calls[0].includes("/api/weather/weatherapi?"));
 assert.ok(!calls[0].includes("key="));
 rows[2].precip_mm=null;
 const missing=await a.collect({name:"Jeddah",lat:21.5,lon:39.2});
 assert.equal(missing.available,false);
 assert.equal(missing.error,"WEATHERAPI_INSUFFICIENT_HOURLY");
 assert.equal(missing.rainAmount,undefined);
 assert.equal((await a.collect({lat:999,lon:39})).available,false);
 console.log("PASS: WeatherAPI proxy-only client, valid hourly horizons, missing data protected and Anwaa disabled");
}
check().catch(e=>{console.error(e);process.exitCode=1});
